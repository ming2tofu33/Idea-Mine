def group_daily_mine_keywords_by_role(
    keywords: list[dict] | None = None,
) -> dict[str, list[dict]]:
    grouped: dict[str, list[dict]] = {role: [] for role in DAILY_MINE_ROLES}
    for keyword in DAILY_MINE_KEYWORDS if keywords is None else keywords:
        grouped[keyword["role"]].append(keyword)
    return grouped


def group_daily_mine_keywords_by_family_and_role(
    keywords: list[dict] | None = None,
) -> dict[str, dict[str, list[dict]]]:
    grouped: dict[str, dict[str, list[dict]]] = {
        family: {role: [] for role in DAILY_MINE_ROLES}
        for family in DAILY_MINE_FAMILIES
    }
    for keyword in DAILY_MINE_KEYWORDS if keywords is None else keywords:
        grouped[keyword["family"]][keyword["role"]].append(keyword)
    return grouped


def validate_daily_mine_keyword_source() -> None:
    seen_slugs: set[str] = set()
    grouped = group_daily_mine_keywords_by_family_and_role([])

    for keyword in DAILY_MINE_KEYWORDS:
        if set(keyword) != {"slug", "label", "role", "family"}:
            raise RuntimeError(f"Invalid keyword shape: {keyword}")
        if keyword["role"] not in DAILY_MINE_ROLES:
            raise RuntimeError(f"Invalid Daily Mine role: {keyword['role']}")
        if keyword["family"] not in DAILY_MINE_FAMILIES:
            raise RuntimeError(f"Invalid Daily Mine family: {keyword['family']}")
        if keyword["slug"] in seen_slugs:
            raise RuntimeError(f"Duplicate Daily Mine keyword slug: {keyword['slug']}")
        seen_slugs.add(keyword["slug"])
        grouped[keyword["family"]][keyword["role"]].append(keyword)

    undersized_buckets = [
        f"{family}/{role}"
        for family in DAILY_MINE_FAMILIES
        for role in DAILY_MINE_ROLES
        if len(grouped[family][role]) < 8
    ]
    if undersized_buckets:
        raise RuntimeError(
            "Daily Mine keyword source has undersized family/role buckets: "
            + ", ".join(undersized_buckets)
        )
